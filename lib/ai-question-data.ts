/**
 * RAG 严格模式：智能匹配问题
 * 
 * 核心规则：
 * 1. 只允许精确匹配（禁止模糊匹配、关键词推断、意图猜测）
 * 2. 如果未检索到知识（retrieved_docs.length === 0），必须返回转人工话术
 * 3. 禁止 fallback 到模型常识
 * 4. 禁止相似话题代答
 * 5. 只允许引用检索到的文本
 * 
 * @param userQuestion 用户输入的问题
 * @param context 聊天上下文（可选，但不再用于意图猜测）
 * @returns 匹配结果对象，包含答案和是否需要转人工
 */
export function findAnswer(
  userQuestion: string,
  context?: { consecutiveMisses?: number; messages?: Array<{ type: string; content: string }> }
): MatchResult {
  const normalizedQuestion = userQuestion.trim().toLowerCase()
  
  // ============================================
  // 任务 1：检查白名单（必须转人工）
  // ============================================
  if (checkBlockedContent(userQuestion)) {
    return {
      answer: BLOCKED_RESPONSE,
      shouldBlock: true,
      shouldGuide: true,
    }
  }

  // ============================================
  // 任务 2：RAG 严格模式 - 只允许精确匹配
  // ============================================
  // 精确匹配：问题完全一致（忽略大小写和前后空格）
  const exactMatch = questionPool.find(
    (item) => item.q.trim().toLowerCase() === normalizedQuestion
  )

  // ============================================
  // 任务 3：禁止意图猜测 - 移除所有模糊匹配
  // ============================================
  // ❌ 已移除：特殊关键词组合匹配
  // ❌ 已移除：关键词匹配（部分匹配）
  // ❌ 已移除：前缀匹配
  // ❌ 已移除：相似问题推断
  // ❌ 已移除：热门问题补答
  // ❌ 已移除：自动联想涨价/促销

  // ============================================
  // 任务 4：RAG 严格模式 - 未检索到知识时转人工
  // ============================================
  if (!exactMatch) {
    // 未检索到知识（retrieved_docs.length === 0）
    // 必须返回转人工话术，禁止 fallback
    return {
      answer: BLOCKED_RESPONSE,
      shouldBlock: false,
      shouldGuide: true,
    }
  }

  // ============================================
  // 任务 5：答案引用绑定 - 只返回检索到的文本
  // ============================================
  // 找到精确匹配，直接返回检索到的答案
  // 禁止添加人工引导（因为这是精确匹配，不需要额外引导）
  return {
    answer: exactMatch.a,
    shouldBlock: false,
    shouldGuide: false,
  }
}
